interface I18nContextValue {
  locale: Locale;
  dir: "ltr" | "rtl";
  setLocale: (loc: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  locale: "en",
  dir: "ltr",
  setLocale: () => {},
  t: (k) => k,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("fastdl_locale") as Locale | null;
    if (saved && (saved === "en" || saved === "fr" || saved === "ar")) {
      queueMicrotask(() => setLocaleState(saved));
    } else {
      const nav = navigator.language.slice(0, 2).toLowerCase();
      if (nav === "fr" || nav === "ar") {
        queueMicrotask(() => setLocaleState(nav));
      }
    }
  }, []);

  const dir: "ltr" | "rtl" = locale === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = dir;
  }, [locale, dir]);

  const setLocale = (loc: Locale) => {
    setLocaleState(loc);
    window.localStorage.setItem("fastdl_locale", loc);
  };

  const t = (key: string) => TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key] ?? key;

  return (
    <I18nContext.Provider value={{ locale, dir, setLocale, t }}>{children}</I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
